async function main() {
  const batch = db.batch();
  for (const pkg of FEATURED_PACKAGES) {
    const ref = db.collection('packages').doc(pkg.id);
    batch.set(ref, {
      ...pkg,
      branch: 'Garden 8',
      status: 'active',
      updatedAt: new Date().toISOString(),
    }, { merge: true });
  }
  await batch.commit();
  console.log(`Synced ${FEATURED_PACKAGES.length} featured Inzan packages in db-inzanathletics.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
